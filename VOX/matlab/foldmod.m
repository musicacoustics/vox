            Hndl.lvoffset(oldMAXM+1:MAXM) = zeros(1,MAXM-oldMAXM);
            Hndl.rmoffset(oldMAXM+1:MAXM) = zeros(1,MAXM-oldMAXM);
            Hndl.rvoffset(oldMAXM+1:MAXM) = zeros(1,MAXM-oldMAXM);


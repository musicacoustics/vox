        % create masses
        for idx = 1:MAXM
            yPos = (bottom+boundfit) + (idx-1)*btnHt;
            %yPos = (idx-1)*a*1000;
            % create entry fields
            % ======================   left fold
            % big darker rectangle for fold mass

            if (Infold.lvoffset(idx) > -10 && Infold.lvoffset(idx) <= 10)
                rectangle('Position',[ -xmax, (idx-1)*a*1000, xmax-1000*(xv(1,idx)-dv/2)+Infold.lvoffset(idx)/10, a*1000], 'FaceColor', [0.5 0.5 0.5]);

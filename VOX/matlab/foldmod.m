                'Units','Normalized',...
                'String', num2str(Infold.lmmfac(idx)), ...
                'TooltipString', ['Set mass factor for left mucosa mass ' num2str(idx)],...
                'Style','edit', ...
                'Horiz','left', ...
                'Callback',['foldmod(''refreshmmfac'', ''value '');']);

            % mvfac
            Hndl.lmvstr(idx) = uicontrol( ... 		% Entry
                'Unit','normal', ...
                'Position',[xPosLeftVocalisMass yPos btnWid btnHt], ...
                'Units','Normalized',...
                'String', num2str(Infold.lmvfac(idx)), ...
                'TooltipString', ['Set mass factor for left vocalis mass ' num2str(idx)],...
                'Style','edit', ...
                'Horiz','left', ...
                'Callback',['foldmod(''refreshmvfac'',''value '');']);

            % mass spring factor
            Hndl.lmmsstr(idx) = uicontrol( ... 		% Entry
                'Unit','normal', ...
                'Position',[xPosLeftMassesSpring yPos btnWid btnHt], ...
                'Units','Normalized',...
                'String', num2str(Infold.lmmsfac(idx)), ...
                'TooltipString', ['Set spring factor for left mucosa to mass spring ' num2str(idx)],...
                'Style','edit', ...
                'Horiz','left', ...
                'Callback',['foldmod(''refreshmmsfac'', ''value '');']);

            % boundary spring factor
            Hndl.lmbsstr(idx) = uicontrol( ... 		% Entry
                'Unit','normal', ...
                'Position',[xPosLeftBoundarySpring yPos btnWid btnHt], ...
                'Units','Normalized',...
                'String', num2str(Infold.lmbsfac(idx)), ...
                'TooltipString', ['Set mass factor for left mass to boundary spring ' num2str(idx)],...
                'Style','edit', ...
                'Horiz','left', ...
                'Callback',['foldmod(''refreshmbsfac'',''value '');']);

            %LEFTMUCOSAOFFSET
            Hndl.lmoffset(idx) = uicontrol( ... 		% Entry
                'Unit','normal', ...
                'Position',[massMucosaLabelLeft+0.01 yPos massEditWid btnHt], ...
                'Units','Normalized',...
                'String', num2str(Infold.lmoffset(idx)), ...
                'TooltipString', ['Set contour shift for left mucosa mass ' num2str(idx)],...
                'Style','edit', ...
                'Min',10, 'Max',10, ...
                'Horiz','center', ...
                'Callback',['foldmod(''refreshOffset'',''string'');']);

            %LEFTVOCALISOFFSET
            Hndl.lvoffset(idx) = uicontrol( ... 		% Entry
                'Unit','normal', ...
                'Position',[massVocalisLabelLeft+0.01 yPos massEditWid btnHt], ...
                'Units','Normalized',...
                'String', num2str(Infold.lvoffset(idx)), ...
                'TooltipString', ['Set contour shift for left vocalis mass ' num2str(idx)],...
                'Style','edit', ...
                'Min',10, 'Max',5, ...
                'Horiz','center', ...
                'Callback',['foldmod(''refreshOffset'',''string'');']);


            % ======================   right fold
            % big darker rectangle for fold mass
            if Infold.rvoffset(idx) >= 0 && Infold.rvoffset(idx) < 10
                rectangle('Position',1000*[ xv(2,idx)-dv/2-Infold.rvoffset(idx)/10000, (idx-1)*a, xmax/1000-xv(2,idx)+dv/2+Infold.rvoffset(idx)/10, a], 'FaceColor', [0.5 0.5 0.5]);
            elseif Infold.rvoffset(idx)>-10 && Infold.rvoffset(idx)<0
                rectangle('Position',1000*[ xv(2,idx)-dv/2+abs(Infold.rvoffset(idx)/10000), (idx-1)*a, xmax/1000-xv(2,idx)+dv/2+abs(Infold.rvoffset(idx)/10), a], 'FaceColor', [0.5 0.5 0.5]);
            else
                error = errordlg('Invalid offset value! -10<Value<10!','VOX-Invalid Offset Value');
                uiwait(error);
                Infold.rvoffset(idx)=0;
                rectangle('Position',1000*[ xv(2,idx)-dv/2-Infold.rvoffset(idx)/10000, (idx-1)*a, xmax/1000-xv(2,idx)+dv/2+Infold.rvoffset(idx)/10, a], 'FaceColor', [0.5 0.5 0.5]);
            end
            % small brighter rectangle for mucosa mass
            if Infold.rmoffset(idx) >= 0 && Infold.rmoffset(idx) < 10
                rectangle('Position',1000*[ xm(2,idx)-dm/2-Infold.rmoffset(idx)/10000, (idx-1)*a, dm+Infold.rmoffset(idx)/10000, a], 'FaceColor' , [0.7 0.7 0.7]);
            elseif Infold.rmoffset(idx) > -10 && Infold.rmoffset(idx) < 0
                rectangle('Position',1000*[ xm(2,idx)-dm/2+abs(Infold.rmoffset(idx)/10000), (idx-1)*a, dm+Infold.rmoffset(idx)/10000, a], 'FaceColor', [0.7 0.7 0.7]);
            else
                error = errordlg('Invalid offset value! -10<Value<10!','VOX-Invalid offset Value');
                uiwait(error);
                Infold.rmoffset(idx)=0;
                rectangle('Position',1000*[ xm(2,idx)-dm/2-Infold.rmoffset(idx)/10000, (idx-1)*a, dm+Infold.rmoffset(idx)/10000, a], 'FaceColor' , [0.7 0.7 0.7]);
            end

            % mmfac
            Hndl.rmmstr(idx) = uicontrol( ... 		% Entry
                'Unit','normal', ...
                'Position',[xPosRightMucosaMass yPos btnWid btnHt], ...
                'Units','Normalized',...
                'String', num2str(Infold.rmmfac(idx)), ...

% gui for folds settings

function out = foldmod(action, var);

global Infold rho c MAXM oldMAXM MAXMdefault Hndl TMAX CALC rvocdefault rtrachdefault IMPORT male_dist female_dist w0 wmax
MAXM = MAXM;
%Infold.mvfac(2,:)=Infold.mvfac(1,:);
%Infold.mmfac(2,:)=Infold.mmfac(1,:);
action;
switch action


    %================================================================
    % initialize
    case 'initialize'
        if voxfigflag('Vocal fold parameters',1) == 1
            set(0,'CurrentFigure',Hndl.ModFoldFig)
            clf;
        else	% create figure
            Hndl.ModFoldFig = figure('visible','on',...
                'NumberTitle','off', ...
                'Name','Vocal fold parameters',...
                'Units','normalized',...
                'Position',[.3 .01 .7 .6]);
            set(Hndl.ModFoldFig,'MenuBar', 'none');


                uiwait(error);
                Infold.lvoffset(idx)=0;
                rectangle('Position',[ -xmax, (idx-1)*a*1000, xmax-1000*(xv(1,idx)-dv/2)+Infold.lvoffset(idx)/10, a*1000], 'FaceColor', [0.5 0.5 0.5]);
            end
            % small brighter rectangle for mucosa mass
            if (Infold.lmoffset(idx) > -10 && Infold.lmoffset(idx) <= 10)
                rectangle('Position',1000*[ -xm(1,idx)-dm/2, (idx-1)*a, dm+Infold.lmoffset(idx)/10000, a], 'FaceColor' , [0.7 0.7 0.7]);
            else
                error = errordlg('Invalid offset value! -10<Value<10!','VOX-Invalid Offset value');
                uiwait(error);
                Infold.lmoffset(idx)=0;
                rectangle('Position',1000*[ -xm(1,idx)-dm/2, (idx-1)*a, dm+Infold.lmoffset(idx)/10000, a], 'FaceColor' , [0.7 0.7 0.7]);

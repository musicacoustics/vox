            'TooltipString', ['Set left mucosa offset'],...
            'Units','Normalized',...
            'String', 'LM', ...
            'Style','text', ...
            'Fontsize',8,...
            'Horizontal','center');
        uicontrol( ...
            'Unit','normal', ...
            'Position',[massVocalisLabelLeft yPos massLabelWid labelHeight], ...
            'TooltipString', ['Set left vocalis offset'],...
            'Units','Normalized',...
            'String', 'LV', ...
            'Style','text', ...
            'Fontsize',8,...
            'Horizontal','center');

        yPos		= 0.05-frmBorder;
        rightleft   = 3*btnWid+1*frmBorder;     % right margin of left box
        axesleft   	= rightleft+3*frmBorder;

        %================================================================
        % Information for all right buttons
        % (no fixed colours: labels and entries use the theme colours)
        bottom			    = 0.06;
        yInitLabelPos	    = 0.90;
        labelWid			= btnWid;
        labelHt				= 0.025;
        btnHt				= 0.022;
        % Spacing between the label and the button for the same command
        btnOffset			= 0.001;

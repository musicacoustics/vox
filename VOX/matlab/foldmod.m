            Infold.rmmfac(oldMAXM+1:MAXM)  = ones(1,MAXM-oldMAXM);
            Infold.lmvfac(oldMAXM+1:MAXM)  = ones(1,MAXM-oldMAXM);
            Infold.rmvfac(oldMAXM+1:MAXM)  = ones(1,MAXM-oldMAXM);

            'Unit','normal', ...
            'Position',[massMucosaLabelRight yPos massLabelWid labelHeight], ...
            'TooltipString', ['Set right mucosa offset'],...
            'Units','Normalized',...
            'String', 'RM', ...
            'Style','text', ...
            'Fontsize',8,...

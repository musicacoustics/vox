        uicontrol( ...
            'Unit','normal', ...
            'Position',[xPosLeftMucosaMass yPos btnWid labelHeight], ...
            'TooltipString', ['Set mass factor for left mucosa mass '],...
            'Units','Normalized',...
            'String', 'LMM', ...
            'Style','text', ...
            'Fontsize',8,...
            'Horizontal','center');
